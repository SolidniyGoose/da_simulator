/* Билет 13. Z-функция, построение за линейное время (алгоритм из конспекта, индексация с 0). */
(function (App) {
  'use strict';
  const { c: C, s: SS } = App.fmt;

  function run({ S }) {
    const n = S.length, Z = new Array(n).fill(null), F = [];
    let l = 0, r = 0, cmp = 0;
    const V = (o) => [['i', o.i ?? '—'], ['l', l], ['r', r], ['k', o.k ?? '—'], ['сравнений', cmp]];
    const push = (line, msg, o = {}) => F.push({ line, msg, Z: Z.slice(), l, r, cmp, vars: V(o), ...o });

    // цикл «while r < n and S[r − l] = S[r]» с кадром на каждое сравнение
    const extend = (i, L1, L2) => {
      for (;;) {
        if (r >= n) {
          push(L1, `r = n = ${n}: дошли до конца строки, сравнивать больше нечего.`, { i, box: r - 1 >= l ? [l, r - 1] : null });
          break;
        }
        cmp++;
        const a = r - l, eq = S[a] === S[r];
        push(L1, eq
          ? `S[r − l] = S[${a}] = ${C(S[a])} и S[r] = S[${r}] = ${C(S[r])} совпали — блок растёт, r = ${r + 1}.`
          : `S[r − l] = S[${a}] = ${C(S[a])} ≠ S[r] = S[${r}] = ${C(S[r])} — совпадение с префиксом закончилось.`,
        { i, box: r - 1 >= l ? [l, r - 1] : null, pair: [a, r, eq] });
        if (!eq) break;
        r++;
      }
      const rr = r;
      Z[i] = r - l;
      r = r - 1;
      push(L2, `Z[${i}] = r − l = ${rr} − ${l} = ${Z[i]}. Затем r = r − 1 = ${r}: теперь r указывает на последний символ Z-блока [${l}, ${r}]${Z[i] === 0 ? ' (блок пустой)' : ''}.`,
        { i, box: r >= l ? [l, r] : null, set: i, big: true });
    };

    push(0, `Строка длины n = ${n}. Храним самый правый найденный Z-блок [l, r]: S[l..r] совпадает с префиксом S[0..r−l]. Z[0] не определяем (по договорённости это 0 или n).`, { big: true });
    for (let i = 1; i < n; i++) {
      if (i > r) {
        push([1, 2], `i = ${i} > r = ${r}: позиция i вне Z-блока, о ней ничего не известно — считаем Z[${i}] честно, сравнивая с префиксом.`, { i, box: r >= l && l > 0 ? [l, r] : null, big: true });
        l = r = i;
        push(3, `l = r = ${i}: начинаем новый блок с позиции i и будем сравнивать S[r − l] с S[r].`, { i, box: null });
        extend(i, 4, 5);
      } else {
        const k = i - l;
        push([1, 6, 7], `i = ${i} ≤ r = ${r}: позиция внутри Z-блока [${l}, ${r}]. Так как S[${l}..${r}] = S[0..${r - l}], позиции i в префиксе соответствует k = i − l = ${k}, и S[i..r] = S[k..${r - l}].`,
          { i, k, box: [l, r], big: true });
        const rest = r - i + 1;
        if (Z[k] < rest) {
          Z[i] = Z[k];
          push([8, 9], `Z[k] = Z[${k}] = ${Z[k]} < r − i + 1 = ${rest}: совпадение с префиксом, начинающееся в k, и первое несовпадение после него целиком лежат внутри копии блока. Значит, в позиции i всё точно так же: Z[${i}] = ${Z[k]} — ни одного сравнения.`,
            { i, k, box: [l, r], set: i, src: k, seg: Z[k] ? [i, i + Z[k] - 1] : null });
        } else {
          push([8, 10], `Z[k] = Z[${k}] = ${Z[k]} ≥ r − i + 1 = ${rest}: известно только, что S[${i}..${r}] совпадает с префиксом длины ${rest}. Что за правой границей блока — не знаем, поэтому продолжаем сравнения.`,
            { i, k, box: [l, r], src: k, seg: [i, r] });
          l = i;
          push(11, `l = ${i}: блок теперь начинается в i. Сравнения продолжаются с r = ${r} (этот символ уже известен, конспект перепроверяет его — лишнее, но безвредное сравнение).`,
            { i, box: [l, r] });
          extend(i, 12, 13);
        }
      }
    }
    push([], `Готово: Z построена. Сравнений символов: ${cmp} (n = ${n}). Это O(n): каждая удачная проверка двигает правую границу блока, неудачная — одна на каждое i.`,
      { done: true, big: true });
    return F;
  }

  function render(f, { S }) {
    const n = S.length, box = f.box, pre = box ? [0, box[1] - box[0]] : null;
    const seg = f.seg, src = f.src;
    const rows = [
      { type: 'idx', n },
      {
        type: 'marks',
        items: [
          f.i != null && { at: f.i, text: 'i' },
          f.k != null && { at: f.k, text: 'k', cls: 'w' },
          !f.done && f.l != null && f.l > 0 && { at: f.l, text: 'l', cls: 'm' },
          !f.done && f.r != null && f.l > 0 && { at: Math.min(f.r, n), text: 'r', cls: 'm' },
        ],
      },
      {
        type: 'chars', label: 'S', chars: S,
        cell: (j) => {
          const c = [];
          if (f.pair && (j === f.pair[0] || j === f.pair[1])) c.push(f.pair[2] ? 'ok' : 'bad', 'focus');
          else if (box && j >= box[0] && j <= box[1]) c.push('blk');
          if (pre && j >= pre[0] && j <= pre[1]) c.push('pre');
          return c.join(' ');
        },
      },
      {
        type: 'spans',
        items: [
          box && { from: box[0], to: box[1], text: `Z-блок [${box[0]}, ${box[1]}]` },
          pre && { from: pre[0], to: pre[1], text: 'его копия в префиксе', cls: 'pre' },
          seg && f.i != null && { from: seg[0], to: seg[1], text: 'совпадает с префиксом', cls: 'occ' },
        ],
      },
      {
        type: 'nums', label: 'Z',
        values: f.Z.map((z, j) => (j === 0 ? '–' : z)),
        cell: (j) => (j === f.set ? 'new' : j === src ? 'src' : ''),
      },
    ];
    return App.strip(n + 1, rows);
  }

  App.register({
    id: 'z', block: 3, num: 13, title: 'Z-функция',
    full: '13. Z-функция, построение за линейное время.',
    modes: [{
      id: 'main', label: 'Построение',
      inputs: [{ id: 'S', label: 'Строка S', value: 'aabxaabxcaabxaabxay', max: 32, w: 22 }],
      presets: [
        { label: 'aabxaab…', v: { S: 'aabxaabxcaabxaabxay' } },
        { label: 'abacaba…', v: { S: 'abacabadabacaba' } },
        { label: 'aaaaaaaa', v: { S: 'aaaaaaaaaa' } },
        { label: 'поиск aba в P$T', v: { S: 'aba$abaababa' } },
      ],
      legend: [['blk', 'Z-блок [l, r]'], ['pre', 'копия блока в префиксе S[0..r−l]'], ['ok', 'совпало'], ['bad', 'не совпало'], ['src', 'Z[k], откуда копируем'], ['new', 'только что вычислено']],
      code: [
        'l = 0;  r = 0',
        'for i = 1 .. n − 1:',
        '  if i > r:                        // вне блока',
        '    l = r = i',
        '    while r < n and S[r − l] = S[r]: r = r + 1',
        '    Z[i] = r − l;  r = r − 1',
        '  else:                            // i внутри [l, r]',
        '    k = i − l',
        '    if Z[k] < r − i + 1:',
        '      Z[i] = Z[k]                   // без сравнений',
        '    else:',
        '      l = i',
        '      while r < n and S[r − l] = S[r]: r = r + 1',
        '      Z[i] = r − l;  r = r − 1',
      ],
      run, render,
    }],
    theory: `
<div class="def"><b>Определение.</b> Z-функция строки S — отображение, которое индексу i (i ≥ 1) сопоставляет Z[i] — длину наибольшей подстроки, начинающейся в позиции i и совпадающей с префиксом S. Z[0] не указывают, либо полагают равным 0 или длине строки.</div>
<p>Пример: S = <code>aabxaab</code> → Z = –, 1, 0, 0, 3, 1, 0.</p>
<p><b>Z-блок</b> позиции i — отрезок [i, i + Z[i] − 1]: он совпадает с префиксом S[0..Z[i]−1]. Алгоритм хранит самый правый из найденных блоков [l, r], то есть S[l..r] = S[0..r−l].</p>

<h3>Идея построения за O(n)</h3>
<ul>
<li><b>i &gt; r</b> (вне блока): о позиции i ничего не известно. Считаем Z[i] честно — сравниваем S[r − l] и S[r], сдвигая r, пока совпадает. Найденный отрезок становится новым блоком [l, r].</li>
<li><b>l &lt; i ≤ r</b> (внутри блока). Раз S[l..r] = S[0..r−l], то S[i..r] = S[k..r−l], где k = i − l. Начало совпадения с префиксом в позиции i повторяет то, что уже посчитано в позиции k:
  <ul>
  <li>если Z[k] &lt; r − i + 1, то совпадение длины Z[k] и первое несовпадение после него лежат внутри копии блока, значит, <b>Z[i] = Z[k]</b> без единого сравнения;</li>
  <li>иначе Z[i] ≥ r − i + 1: S[i..r] уже совпадает с префиксом, а дальше блока информации нет. Продолжаем сравнения за r и получаем новый блок с l = i.</li>
  </ul></li>
</ul>

<h3>Алгоритм (как в конспекте)</h3>
<ol>
<li>l = 0, r = 0.</li>
<li>Для i от 1 до n − 1:
 <ul><li>если i &gt; r: l = r = i; пока r &lt; n и S[r − l] = S[r], увеличиваем r; Z[i] = r − l; r = r − 1;</li>
 <li>иначе k = i − l; если Z[k] &lt; r − i + 1, то Z[i] = Z[k]; иначе l = i, пока r &lt; n и S[r − l] = S[r] увеличиваем r, Z[i] = r − l, r = r − 1.</li></ul></li>
</ol>
<p class="note">Внутри цикла r — первая ещё не проверенная позиция; после «r = r − 1» r снова указывает на последний символ блока.</p>

<h3>Доказательство линейности</h3>
<div class="thm"><b>Теорема.</b> Z-функция строки длины n строится за O(n).</div>
<div class="proof">
<p>Кроме циклов сравнения, каждая итерация по i делает O(1) действий — всего O(n).</p>
<p><b>Неудачные сравнения.</b> Неудачное сравнение завершает цикл while, поэтому на каждое i приходится не больше одного — всего не больше n.</p>
<p><b>Удачные сравнения.</b> Каждое удачное сравнение сдвигает r на 1. Правая граница самого правого блока никогда не уменьшается: в случае i &gt; r сравнения начинаются с позиции r + 1 = i, а в случае Z[k] ≥ r − i + 1 новый блок доходит как минимум до старого r. Граница не превосходит n, поэтому удачных сравнений, двигающих её вправо, не больше n. В варианте из конспекта после l = i первое сравнение перепроверяет уже известный символ S[r]; это добавляет не больше одного лишнего удачного сравнения на i.</p>
<p>Итого не больше ≈ 3n сравнений (≤ 2n, если начинать сравнение с r + 1) и O(n) времени, O(n) памяти.</p>
</div>

<h3>Применение: поиск образца</h3>
<p>Строим Z-функцию строки P$T, где $ не встречается ни в P, ни в T. Тогда P входит в T с позиции s ⇔ Z[m + 1 + s] = m. Время O(n + m). Попробуй пример «поиск aba в P$T»: значения Z = 3 отмечают вхождения.</p>
<p>Z-функция также лежит в основе построения префикс-функции для КМП (билет 14) и таблиц N, L′, l′ для Бойера-Мура (билет 15).</p>`,
    quiz: {
      intro: 'Заполни Z-функцию строки (Z[0] не заполняется). Считай руками, как на экзамене, потом нажми «Проверить».',
      arrays: (s) => [{ key: 'Z', label: 'Z', ans: App.algo.z(s).map(String), skip: [0] }],
    },
  });
})(window.App);
