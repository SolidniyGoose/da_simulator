/* Билет 11. PATRICIA trie (как в конспекте): корень-заголовок с битом 0 и одной левой ссылкой,
   у вершин — значение, номер проверяемого бита (с 1, слева), левая и правая ссылки.
   Ссылка прямая, если ведёт к вершине с бо́льшим номером бита, иначе обратная. */
(function (App) {
  'use strict';
  const { s: SS } = App.fmt;

  const parseOps = (s) => {
    const out = [];
    for (const t of s.split(/[\s,;]+/).filter(Boolean)) {
      const m = /^([+\-?]?)([01]{2,8})$/.exec(t);
      if (!m) return { err: `Не понял «${t}». Пиши двоичные слова одной длины (2–8 бит): «1001» — вставка, «-1001» — удаление, «?1001» — поиск.` };
      out.push({ t: m[1] || '+', k: m[2] });
    }
    if (new Set(out.map((o) => o.k.length)).size > 1) return { err: 'Все слова должны быть одной длины (значение кодируется фиксированным числом бит).' };
    return { ops: out };
  };
  const opName = (o) => ({ '+': 'вставка', '-': 'удаление', '?': 'поиск' })[o.t] + ' ' + o.k;

  function run({ ops: src }) {
    const { ops } = parseOps(src);
    const N = {}, F = [];
    let root = null, seq = 0, opi = -1;
    const bit = (a, i) => a[i - 1] === '1';
    const add = (key, b) => { const id = ++seq; N[id] = { id, key, bit: b, l: null, r: null }; return id; };
    const snap = () => {
      const S = {}, links = [];
      for (const id in N) {
        const x = N[id];
        S[id] = { id: x.id, key: x.key, bit: x.bit, l: null, r: null, p: null };
      }
      for (const id in N) {
        const x = N[id];
        for (const sd of ['l', 'r']) {
          const t = x[sd];
          if (t == null) continue;
          if (N[t].bit > x.bit) { S[id][sd] = t; S[t].p = +id; } else links.push({ from: +id, to: t, side: sd });
        }
      }
      return { S: { N: S, root }, links };
    };
    const push = (line, msg, x = {}) => {
      const { S, links } = snap();
      F.push({ line, msg, S, links, ops, opi, ...x, vars: [['операция', opi >= 0 && opi < ops.length ? opName(ops[opi]) : '—'], ['вершин', Object.keys(N).length], ['биты пути', x.seq ? x.seq.join(' < ').replace(/ < (\d+)$/, x.stop ? ' ≥ $1' : ' < $1') : '—']] });
    };
    const nm = (v) => (v === root ? `корень ${N[v].key}` : `${N[v].key}`);

    // поиск с кадрами; возвращает {x, p, pp, seq}
    const search = (a, line, quiet) => {
      let pp = null, p = root, x = N[root].l;
      const sq = [0], path = [root];
      if (!quiet) push(line, `Из корня сразу переходим по его (единственной) левой ссылке → ${nm(x)}.`, { mark: App.markPath(path, x), seq: sq.slice() });
      while (N[x].bit > N[p].bit) {
        sq.push(N[x].bit);
        path.push(x);
        const b = bit(a, N[x].bit);
        if (!quiet) push(line, `Вершина ${N[x].key}, проверяемый бит ${N[x].bit}: в ${a} бит ${N[x].bit} = ${b ? 1 : 0} → идём по ${b ? 'правой' : 'левой'} ссылке${N[b ? N[x].r : N[x].l].bit > N[x].bit ? ' (прямой — вниз)' : ' (обратной — вверх или в себя)'}.`, { mark: App.markPath(path, x), seq: sq.slice() });
        pp = p; p = x; x = b ? N[x].r : N[x].l;
      }
      sq.push(N[x].bit);
      return { x, p, pp, seq: sq, path };
    };

    const doSearch = (a) => {
      push(0, `Поиск ${a}.`, { big: true });
      if (root == null) { push(0, 'Дерево пустое.', {}); return; }
      const r = search(a, 1);
      const ok = N[r.x].key === a;
      push([2, 3], `Пришли в ${N[r.x].key} с битом ${N[r.x].bit}: последовательность номеров битов ${r.seq.slice(0, -1).join(' < ')} ≥ ${r.seq[r.seq.length - 1]} перестала возрастать — прошли по обратной ссылке. Сравниваем слово целиком: ${N[r.x].key} ${ok ? '=' : '≠'} ${a} — ${ok ? 'нашли' : 'искомого слова нет'}.`, { mark: App.markPath(r.path, r.x, { [r.x]: ok ? 'new' : 'del' }), seq: r.seq, stop: true, big: true });
    };

    const insert = (a) => {
      push(4, `Вставка ${a}.`, { big: true });
      if (root == null) {
        root = add(a, 0);
        N[root].l = root;
        push(4, `Дерево пустое — ${a} становится корнем с номером бита 0, его левая ссылка ведёт сама на себя.`, { mark: { [root]: 'new' }, big: true });
        return;
      }
      const r = search(a, 5);
      const W = N[r.x].key;
      if (W === a) { push(5, `Нашли ${a} — вставка не требуется.`, { mark: { [r.x]: 'cur' }, seq: r.seq, stop: true }); return; }
      let j = 1;
      while (a[j - 1] === W[j - 1]) j++;
      push(5, `Поиск дал наиболее похожее слово W = ${W}. Первый отличающийся бит X = ${a} и W: j = ${j} (${a.slice(0, j - 1)}<b>${a[j - 1]}</b>… против ${W.slice(0, j - 1)}<b>${W[j - 1]}</b>…).`, { mark: { [r.x]: 'cur' }, seq: r.seq, stop: true, big: true });
      let p = root, x = N[root].l;
      const sq = [0], path = [root];
      while (N[x].bit > N[p].bit && N[x].bit < j) {
        sq.push(N[x].bit); path.push(x);
        p = x; x = bit(a, N[x].bit) ? N[x].r : N[x].l;
      }
      const t = add(a, j);
      const xj = bit(a, j);
      if (xj) { N[t].r = t; N[t].l = x; } else { N[t].l = t; N[t].r = x; }
      const ps = p === root ? 'l' : bit(a, N[p].bit) ? 'r' : 'l';
      push(6, `Ищем, куда вставить j = ${j}, чтобы пройденные биты шли по возрастанию: ${sq.join(' < ')} < <b>${j}</b>${N[x].bit > N[p].bit ? ` < ${N[x].bit}` : ''}. Разбиваем ссылку ${nm(p)} → ${nm(x)}${N[x].bit > N[p].bit ? '' : ' (обратную)'}.`, { mark: App.markPath(path, p, { [x]: 'rot' }), seq: sq });
      N[p][ps] = t;
      push(7, `Ссылка от родителя ${nm(p)} теперь ведёт в X = ${a} (бит ${j}). У X ссылка, соответствующая X_${j} = ${xj ? 1 : 0}, — ${xj ? 'правая' : 'левая'} — ведёт в себя, а другая — в ${nm(x)}${x === p ? ' (родитель и ребёнок — одна вершина, поэтому обе ссылки X обратные)' : ''}.`, { mark: { [t]: 'new', [p]: 'path', [x]: 'rot' }, big: true });
    };

    const remove = (a) => {
      push(8, `Удаление ${a}: ищем вершину.`, { big: true });
      if (root == null) { push(8, 'Дерево пустое.', {}); return; }
      const r = search(a, 8);
      if (N[r.x].key !== a) { push(8, `Пришли в ${N[r.x].key} ≠ ${a} — слова нет.`, { mark: { [r.x]: 'del' }, seq: r.seq, stop: true }); return; }
      const X = r.x, Q = r.p, M = r.pp;
      if (X === root && N[root].l === root) {
        push(9, `Случай 1: X = ${a} — корень, и его ссылка ведёт на себя — это единственное слово. Удаляем корень, дерево пустое.`, { mark: { [X]: 'del' }, big: true });
        delete N[root]; root = null;
        push(9, 'Готово.', {});
        return;
      }
      if (Q === X) {
        const sd = N[X].l === X ? 'l' : 'r', os = sd === 'l' ? 'r' : 'l', L = N[X][os];
        const ms = N[M].l === X ? 'l' : 'r';
        push(10, `Случай 2: у X = ${a} одна ссылка (${sd === 'l' ? 'левая' : 'правая'}) ведёт на себя — на X больше никто обратной ссылкой не указывает. У X есть родитель ${nm(M)}: соединяем его с ${N[L].bit > N[X].bit ? `ребёнком X — ${nm(L)}` : `тем, куда вела вторая ссылка X (${nm(L)})`}, саму X удаляем.`, { mark: { [X]: 'del', [M]: 'path', [L]: 'rot' }, big: true });
        N[M][ms] = L;
        delete N[X];
        push(10, 'Готово.', { mark: { [M]: 'cur' } });
        return;
      }
      // общий случай: на X обратной ссылкой указывает другая вершина Q
      const qs = Q === root ? 'l' : bit(a, N[Q].bit) ? 'r' : 'l', os = qs === 'l' ? 'r' : 'l';
      const pr = search(N[Q].key, 11, true), P = pr.p;
      const L0 = N[Q][os], L = L0 === Q ? X : L0;
      const ms = N[M].l === Q ? 'l' : 'r';
      push(11, `${X === root ? 'Случай 1: X — корень, но на него указывает обратной ссылкой вершина' : 'Случай 3: у X две ссылки не на себя. Ищем вершину, которая обратной ссылкой ссылается на X, —'} Q = ${N[Q].key}. У Q родитель M = ${nm(M)}, сын N = ${L0 === Q ? 'сама Q (ссылка в себя)' : nm(L0)}, на Q обратной ссылкой указывает P = ${nm(P)}.`, { mark: { [X]: 'del', [Q]: 'rot', [M]: 'path', ...(P !== Q ? { [P]: 'cur' } : {}) }, big: true });
      N[X].key = N[Q].key;
      push(12, `Копируем значение Q (${N[Q].key}) в X${X === root ? ' (только значение — номер бита корня остаётся 0)' : ` (номер бита X остаётся ${N[X].bit})`}. Теперь вершина Q лишняя.`, { mark: { [X]: 'new', [Q]: 'del' } });
      N[M][ms] = L;
      if (P !== Q) { const psd = N[P].l === Q ? 'l' : 'r'; N[P][psd] = X; }
      delete N[Q];
      push(12, `Убираем Q: родитель M = ${nm(M)} теперь ссылается на ${L === X ? 'X (Q ссылалась сама на себя)' : nm(L)}, а обратная ссылка P, указывавшая на Q, теперь указывает на X (там лежит значение Q).`, { mark: { [X]: 'new', [M]: 'path' }, big: true });
    };

    push([], 'PATRICIA: в каждой вершине — значение и номер проверяемого бита. Прямые ссылки (сплошные) ведут вниз к большему номеру бита, обратные (пунктир) — к вершине выше или в себя. На каждую вершину указывает ровно одна обратная ссылка.', { big: true });
    for (opi = 0; opi < ops.length; opi++) {
      const o = ops[opi];
      ({ '+': insert, '-': remove, '?': doSearch })[o.t](o.k);
    }
    opi = ops.length;
    push([], `Готово. Слова: ${Object.values(N).map((x) => x.key).sort().join(', ') || '—'}. Вершин ровно столько, сколько слов.`, { big: true });
    return F;
  }

  App.register({
    id: 'patricia', block: 2, num: 11, title: 'PATRICIA',
    full: '11. PATRICIA Trie. Основные операции. Оценка алгоритмической сложности выполнения операций.',
    modes: [{
      id: 'main', label: 'Операции',
      note: 'Бейдж над вершиной — номер проверяемого бита (биты считаются с 1 слева). Сплошные стрелки — прямые ссылки, пунктир — обратные.',
      inputs: [{ id: 'ops', label: 'Операции', raw: true, value: '0001 1001 1000 1100 1101 0011 ?1000 ?1010', max: 120, w: 30 }],
      validate: (v) => { const r = parseOps(v.ops); return r.err || (r.ops.filter((o) => o.t === '+').length > 14 ? 'Не больше 14 вставок.' : null); },
      presets: [
        { label: 'пример из конспекта', v: { ops: '0001 1001 1000 1100 1101 0011 ?1000 ?1010' } },
        { label: 'удаления: все случаи', v: { ops: '0001 1001 1000 1100 1101 0011 -1101 -1001 -0001' } },
        { label: '3 бита', v: { ops: '000 111 010 101 ?011' } },
      ],
      legend: [['ring', 'путь / текущая'], ['rot', 'разбиваемая ссылка / Q'], ['ok', 'новая'], ['bad', 'удаляемая / не та'], ['sl', 'обратная ссылка']],
      code: [
        'поиск a: из корня — по левой ссылке',
        '  в вершине с битом i: a_i = 1 → правая ссылка, иначе левая',
        '  номера битов перестали расти (обратная ссылка) → стоп',
        '  сравниваем найденное слово с a',
        'вставка X: пустое дерево → X в корень, левая ссылка в себя',
        '  иначе поиск X → W;  j = первый отличающийся бит X и W',
        '  находим место j среди пройденных битов (по возрастанию)',
        '  родитель → X;  ссылка X по биту X_j → в себя, другая → ребёнку',
        'удаление: ищем вершину X',
        '  1) X — корень и ссылка в себя → удалить; иначе как в 3)',
        '  2) у X одна ссылка в себя → соединить родителя с ребёнком X',
        '  3) Q — вершина с обратной ссылкой на X, M — её родитель, P — ссылается на Q',
        '     значение Q → в X;  M → ребёнок Q;  P → X;  удалить Q',
      ],
      run,
      render: (f) => `<div class="chips"><b>Операции:</b>${f.ops.map((o, i) => `<span class="${i === f.opi ? 'on' : i < f.opi ? 'ok' : ''}">${o.t === '+' ? '' : o.t}${o.k}</span>`).join('')}</div>` +
        (f.S.root == null ? '<p class="hint">Дерево пустое.</p>' : App.btree(f.S, { label: (id) => f.S.N[id].key, badge: (id) => String(f.S.N[id].bit), cls: (id) => (f.mark || {})[id], links: f.links })),
    }],
    theory: `
<div class="def"><b>PATRICIA</b> — Practical Algorithm To Retrieve Information Coded In Alphanumeric: «практический алгоритм извлечения информации, закодированной буквами и цифрами». PATRICIA trie состоит из корня и вершин, каждая из которых содержит:
<ul><li>значение (кодируется ограниченным числом бит);</li><li>номер проверяемого бита;</li><li>правую и левую ссылки.</li></ul>
У корня есть только значение и левая ссылка (его номер бита 0 — он нужен, чтобы остановить алгоритм при возврате в корень).</div>
<p>Ссылки бывают двух видов:</p>
<ul><li><b>прямые</b> ведут вниз по структуре и гарантируют, что следующий номер проверяемого бита <b>больше</b> текущего;</li>
<li><b>обратные</b> указывают либо на себя, либо на вершину выше и гарантируют, что следующий номер бита <b>не больше</b> текущего.</li></ul>
<p><b>Важное свойство:</b> на каждую вершину указывает ровно одна обратная ссылка. Вершин ровно столько, сколько хранимых слов — в отличие от trie, где вершин может быть порядка суммарной длины.</p>

<h3>Поиск</h3>
<p>Пусть номер проверяемого бита текущей вершины i, искомое слово a.</p>
<ol><li>Из корня сразу переходим по его ссылке.</li>
<li>Если a<sub>i</sub> = 1 — идём по правой ссылке, иначе по левой.</li>
<li>Если последовательность номеров проверяемых битов перестала возрастать (i<sub>0</sub> &lt; i<sub>1</sub> &lt; … &lt; i<sub>k−1</sub> ≥ i<sub>k</sub>), проверяем найденное слово: совпадает с искомым — нашли, иначе искомого слова в дереве нет.</li></ol>
<p><b>Важное свойство перехода по прямым ссылкам:</b> он отрезает поддеревья, в которых гарантированно нет искомого слова — все слова, до которых можно дойти дальше, совпадают с искомым на всех проверенных битах. Пример из конспекта: поиск 1000 в дереве слов 0001, 1001, 1000, 1100, 1101, 0011 проходит биты 0 &lt; 1 &lt; 2 &lt; 4 ≥ 4 и заканчивается в 1000.</p>

<h3>Вставка X</h3>
<ul><li>Если дерево пустое — X помещается в корень, его левая ссылка ведёт сама на себя.</li>
<li>Иначе ищем X в дереве и получаем наиболее похожее слово W.
 <ul><li>Ищем первый отличающийся бит j между X и W; если его нет — X уже есть, вставка не требуется.</li>
 <li>Смотрим, куда вставить j, чтобы пройденные биты шли по возрастанию (последний пройденный бит, по обратной ссылке, отбрасываем). Например, пройдено 0 &lt; 1 &lt; 5, а j = 2 — тогда 0 &lt; 1 &lt; j &lt; 5.</li>
 <li>Место, куда встало j, соответствует ссылке, которую нужно разбить (в примере — ссылка из вершины с битом 1 в вершину с битом 5).</li>
 <li>Ссылка от родителя теперь ведёт в X; у X ссылка, соответствующая X<sub>j</sub>, ведёт в себя (X<sub>j</sub> = 0 — левая в себя, иначе правая), а другая — в ребёнка. Если родитель и ребёнок — одна вершина, у X обе ссылки обратные.</li></ul></li></ul>

<h3>Удаление</h3>
<p>Ищем вершину X с данным значением. Далее:</p>
<ol><li><b>X — корень:</b> если его ссылка ведёт на себя — удаляем корень, и всё. Иначе ищем, кто ссылается на корень обратной ссылкой, копируем его значение в корень (только значение, проверяемый бит остаётся нулём) и удаляем ту вершину (как в случае 3).</li>
<li><b>Одна ссылка X прямая, другая ведёт на себя.</b> Тогда у X есть родитель: соединяем родителя с ребёнком X, саму вершину удаляем.</li>
<li><b>Обе ссылки X ведут не на себя</b> (например, прямые, на вершины A, B). Ищем вершину Q, которая обратной ссылкой ссылается на X. У Q есть родитель M, сын N и вершина P, которая ссылается на Q обратной ссылкой. Копируем значение Q в X; M теперь ссылается на N (вторую ссылку Q); обратная ссылка P теперь ведёт в X; Q удаляем. Порядок не нарушается: Q лежит в поддереве X и совпадает с X на всех битах, проверенных выше X.</li></ol>

<h3>Сложность</h3>
<ul><li>Поиск, вставка, удаление — O(w) проверок битов и одно сравнение слов целиком, где w — длина слова в битах: номера битов на пути строго растут, поэтому шагов не больше w.</li>
<li>Глубина не больше min(w, n): номера битов на пути строго растут, а вершин всего n. Поэтому для длинных ключей операции идут за O(w), а не O(log n) сравнений целых ключей, как в деревьях поиска.</li>
<li>Память — ровно n вершин на n слов, без «пустых» вершин с одним ребёнком, как в обычном trie.</li></ul>`,
  });
})(window.App);
