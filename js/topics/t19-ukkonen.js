/* Билет 19. Алгоритм Укконена: суффиксные связи, прыжки по счётчику, линейность. Изложение по Гасфилду, индексы с 1. */
(function (App) {
  'use strict';
  const ST = App.st, { c: C, s: SS, sub } = App.fmt;

  function run({ S, dollar }) {
    const str = dollar && !S.endsWith('$') ? S + '$' : S;
    const m = str.length, s = ' ' + str;
    const t = ST.create(), nodes = t.nodes, F = [];
    let e = 1, ji = 1, phase = 1;
    const cnt = { ext: 1, jumps: 0, links: 0 };
    const name = (id) => ST.name(nodes, id);
    const ps = (id) => SS(ST.pathStr(nodes, id, s, e));
    const apStr = (p) => p.child >= 0
      ? `(${p.node === 0 ? 'корень' : nodes[p.node].nm}, ${s[nodes[p.child].a]}, ${p.k})`
      : `(${p.node === 0 ? 'корень' : nodes[p.node].nm}, —, 0)`;
    let pos = { node: 0, child: -1, k: 0 };
    const V = (o) => [['фаза', `i + 1 = ${phase}`], ['j', o.j ?? '—'], ['jᵢ', ji], ['e', e], ['β', o.beta != null ? SS(o.beta) : '—'], ['акт. точка', apStr(pos)], ['явных продолжений', cnt.ext], ['прыжков', cnt.jumps]];
    const push = (o) => F.push({ nodes: ST.snap(t), e, str, vars: V(o), ...o });
    const at = (p) => (p.child >= 0 ? { on: p.child, k: p.k } : { cur: p.node });

    // спуск по S[a..b] от узла from прыжками по счётчику
    const walk = (from, a, b, o) => {
      let cur = from, g = b - a + 1;
      while (g > 0) {
        const c = nodes[cur].ch[s[a]], L = ST.len(nodes[c], e), lab = ST.label(nodes[c], s, e);
        cnt.jumps++;
        if (g >= L) {
          pos = { node: c, child: -1, k: 0 };
          push({ ...o, msg: `Прыжок по счётчику: осталось пройти ${g} симв. Ребро на ${C(s[a])} — ${SS(lab)}, длина ${L} ≤ ${g}: перепрыгиваем его целиком за O(1), символы не сравниваем — путь точно есть в дереве.`, hl: { cur: c, path: [c] } });
          cur = c; a += L; g -= L;
        } else {
          pos = { node: cur, child: c, k: g };
          push({ ...o, msg: `Осталось ${g} симв., а ребро на ${C(s[a])} — ${SS(lab)} длины ${L} > ${g}. Останавливаемся внутри него после ${g} симв. Это и есть конец β.`, hl: { on: c, k: g } });
          return;
        }
      }
      pos = { node: cur, child: -1, k: 0 };
    };

    const l1 = ST.addLeaf(t, s, 0, 1, ST.E, 1);
    push({ line: 0, big: true, j: 1, beta: '', msg: `Фаза 1: I₁ — одно ребро из корня в лист 1 с меткой S[1] = ${C(s[1])}. Метку храним не строкой, а парой индексов [1, e], где e — общий «конец» всех листьев. j₁ = 1.`, hl: { fresh: [l1] }, strip: { cur: 1, dimFrom: 2 } });

    for (let i = 1; i < m; i++) {
      phase = i + 1;
      const x = s[i + 1];
      e = i + 1;
      push({ line: [1, 2], big: true, msg: `Фаза ${i + 1}: добавляем S[${i + 1}] = ${C(x)}. Присваиваем e = ${e} — метки всех листьев [p, e] удлинились сами. Это правило 1 для продолжений 1…${ji} за O(1): однажды лист — всегда лист.`, hl: {}, strip: { cur: i + 1, dimFrom: i + 2 } });
      let lastNew = -1, stopped = false;
      for (let j = ji + 1; j <= i + 1; j++) {
        cnt.ext++;
        const beta = s.slice(j, i + 1);
        const strip = { blk: [j, i], cur: i + 1, dimFrom: i + 2 };
        const o = { j, beta, strip };
        if (j === ji + 1) {
          push({ ...o, line: 3, msg: beta === ''
            ? `Продолжение ${j}: β = S[${j}..${i}] пустая, её конец — корень.`
            : `Продолжение ${j} — первое явное в фазе. Конец β = S[${j}..${i}] = ${SS(beta)} уже известен: здесь остановилась прошлая фаза (правило 3), искать не нужно.`,
          hl: at(pos) });
        } else {
          const u = pos.node;
          if (u !== 0 && nodes[u].sl >= 0) {
            const sv = nodes[u].sl;
            cnt.links++;
            pos = { node: sv, child: -1, k: 0 };
            push({ ...o, line: [3, 4, 5], msg: `Продолжение ${j}: стоим в конце S[${j - 1}..${i}] — это ${name(u)} (путь ${ps(u)}). У него уже есть суффиксная связь, поэтому подниматься не нужно (γ = ε). Переходим по связи в ${name(sv)} (путь ${ps(sv)}) — это конец β = ${SS(beta)}.`, hl: { cur: sv, link: [u, sv] } });
          } else if (u === 0) {
            push({ ...o, line: [3, 4, 6], msg: `Продолжение ${j}: начинаем от корня и спускаемся по β = ${SS(beta)}.`, hl: { cur: 0 } });
            walk(0, j, i, { ...o, line: 6 });
          } else {
            const v = nodes[u].p, ga = nodes[u].a, gb = ST.end(nodes[u], e), gamma = s.slice(ga, gb + 1);
            pos = { node: v, child: -1, k: 0 };
            push({ ...o, line: [3, 4], msg: `Продолжение ${j}: стоим в конце S[${j - 1}..${i}] — ${name(u)}. Он создан в прошлом продолжении и суффиксной связи ещё не имеет. Поднимаемся на одно ребро к ${name(v)}; пройденная метка γ = ${SS(gamma)}.`, hl: { cur: v, path: [u] } });
            if (v === 0) {
              push({ ...o, line: 6, msg: `${name(v)} — корень, связи у него нет. Спускаемся от корня по β = S[${j}..${i}] = ${SS(beta)} (это γ без первого символа) прыжками по счётчику.`, hl: { cur: 0 } });
              walk(0, j, i, { ...o, line: 6 });
            } else {
              const sv = nodes[v].sl;
              cnt.links++;
              pos = { node: sv, child: -1, k: 0 };
              push({ ...o, line: 5, msg: `Переходим по суффиксной связи ${name(v)} → ${name(sv)}: путь ${ps(v)} → ${ps(sv)} (отбросили первый символ). Теперь спускаемся по γ = ${SS(gamma)} прыжками по счётчику.`, hl: { cur: sv, link: [v, sv] } });
              walk(sv, ga, gb, { ...o, line: 5 });
            }
          }
        }

        // применяем правило в конце β
        const nextCh = pos.child >= 0 ? s[nodes[pos.child].a + pos.k] : null;
        const has = pos.child >= 0 ? nextCh === x : nodes[pos.node].ch[x] != null;
        if (has) {
          let lm = '';
          const link = lastNew >= 0 && pos.child < 0 ? [lastNew, pos.node] : null;
          if (link) { nodes[lastNew].sl = pos.node; lm = ` Заодно узел ${nodes[lastNew].nm} из прошлого продолжения получает суффиксную связь → ${name(pos.node)}.`; }
          ji = j - 1;
          push({ ...o, line: link ? [7, 8, 10] : [7, 8], big: true, msg: `За концом β = ${SS(beta)} уже идёт ${C(x)} → правило 3: ничего не делаем. Раз путь ${SS(beta + x)} есть в дереве, то есть и все его суффиксы — продолжения ${j + 1}…${i + 1} тоже правило 3. Фаза заканчивается досрочно: j${sub(i + 1)} = ${j - 1}.${lm}`, hl: { ...at(pos), next: true, link } });
          // для следующей фазы конец S[j..i+1] — на один символ дальше
          if (pos.child < 0) {
            const c = nodes[pos.node].ch[x];
            pos = !nodes[c].leaf && ST.len(nodes[c], e) === 1 ? { node: c, child: -1, k: 0 } : { node: pos.node, child: c, k: 1 };
          } else {
            const k = pos.k + 1, c = pos.child;
            pos = !nodes[c].leaf && k === ST.len(nodes[c], e) ? { node: c, child: -1, k: 0 } : { node: pos.node, child: c, k };
          }
          stopped = true;
          break;
        }
        let par = pos.node, w = -1;
        if (pos.child >= 0) { w = ST.split(t, s, pos.child, pos.k); par = w; }
        const lf = ST.addLeaf(t, s, par, i + 1, ST.E, j);
        let lm = '';
        const link = lastNew >= 0 ? [lastNew, par] : null;
        if (link) { nodes[lastNew].sl = par; lm = ` Узел ${nodes[lastNew].nm}, созданный в прошлом продолжении, получает суффиксную связь → ${name(par)} (по лемме конец β всегда узел).`; }
        push({ ...o, line: link ? [9, 10] : 9, big: !!(w >= 0 || link), msg: (w >= 0
          ? `Посреди ребра за β идёт ${C(nextCh)} ≠ ${C(x)} → правило 2: делим ребро новым внутренним узлом ${nodes[w].nm} и вешаем лист ${j} с меткой [${i + 1}, e].`
          : `Из ${name(par)} нет ребра на ${C(x)} → правило 2: добавляем лист ${j} с меткой [${i + 1}, e].`) + lm,
        hl: { fresh: [lf, w], cur: par, link } });
        lastNew = w;
        pos = { node: par, child: -1, k: 0 };
      }
      if (!stopped) {
        ji = i + 1;
        pos = { node: 0, child: -1, k: 0 };
        push({ line: 11, msg: `Все продолжения фазы ${i + 1} были явными (правило 3 не встретилось): j${sub(i + 1)} = ${i + 1}. Следующая фаза начнёт с пустой β, то есть с корня.`, hl: {}, strip: { blk: [1, i + 1], dimFrom: i + 2 } });
      }
    }
    const leaves = nodes.filter((z) => z.leaf).length, miss = [];
    for (let j = 1; j <= m; j++) if (!nodes.some((z) => z.leaf === j)) miss.push(j);
    push({ line: [], big: true, msg: (miss.length
      ? `Готово: неявное дерево Iₘ. Листьев ${leaves} из ${m}: суффиксы ${miss.join(', ')} кончаются внутри дерева. Включи «дописать $» — получится настоящее суффиксное дерево.`
      : `Готово: суффиксное дерево, ${m} листьев — по одному на суффикс.`) +
      ` Явных продолжений: ${cnt.ext} ≤ 2m = ${2 * m}. Прыжков по счётчику: ${cnt.jumps}, переходов по суффиксным связям: ${cnt.links} — всё O(m).`, hl: {}, strip: {} });
    return F;
  }

  App.register({
    id: 'ukkonen', block: 4, num: 19, title: 'Алгоритм Укконена',
    full: '19. Алгоритм Укконена. Суффиксные связи и прыжки по счетчику. Доказательство линейности.',
    modes: [{
      id: 'main', label: 'Построение',
      note: 'Индексация с 1, как у Гасфилда: фаза i + 1 добавляет символ S[i + 1], продолжение j отвечает суффиксу S[j..i + 1]. Пунктир — суффиксные связи.',
      inputs: [
        { id: 'S', label: 'Строка S', value: 'abcabxabcd', max: 16, w: 14 },
        { id: 'dollar', label: 'дописать $', type: 'check', value: false },
        { id: 'idx', label: 'метки рёбер индексами [p, e]', type: 'check', value: false },
      ],
      presets: [
        { label: 'abcabxabcd', v: { S: 'abcabxabcd', dollar: false } },
        { label: 'xabxac', v: { S: 'xabxac', dollar: false } },
        { label: 'xabxa (неявное)', v: { S: 'xabxa', dollar: false } },
        { label: 'mississippi$', v: { S: 'mississippi', dollar: true } },
        { label: 'aabaabaab$', v: { S: 'aabaabaab', dollar: true } },
      ],
      legend: [['blk', 'β = S[j..i]'], ['new', 'S[i+1] / текущий узел'], ['ok', 'новые узлы и рёбра'], ['sl', 'суффиксная связь']],
      code: [
        'I₁: корень → лист 1 с меткой [1, e];  j₁ = 1',
        'for i = 1 .. m − 1:                         // фаза i + 1',
        '  e = i + 1                                 // правило 1 для листьев 1..jᵢ',
        '  for j = jᵢ + 1 .. i + 1:                  // явные продолжения',
        '    if j > jᵢ + 1: от конца S[j−1..i] вверх к узлу v (≤ 1 ребро), γ — метка',
        '      v ≠ корень: v → s(v), спуск по γ прыжками по счётчику',
        '      v = корень: спуск от корня по S[j..i] прыжками',
        '    if за концом S[j..i] уже идёт S[i+1]:',
        '      правило 3: jᵢ₊₁ = j − 1;  конец фазы',
        '    else: правило 2 — лист j (посреди ребра — новый узел w)',
        '    если в продолжении j − 1 создан w′: s(w′) = узел конца S[j..i]',
        '  если правила 3 не было: jᵢ₊₁ = i + 1',
      ],
      run,
      render: (f, v) => ST.render(f, { idx: v.idx }),
    }],
    theory: `
<p>Алгоритм Укконена — это простейший алгоритм «фазы и продолжения» из билета 18, ускоренный до O(m) пятью приёмами. Индексы с 1: фаза i + 1 строит I<sub>i+1</sub> из I<sub>i</sub>, продолжение j добавляет символ S[i+1] к концу β = S[j..i].</p>

<h3>1. Суффиксные связи</h3>
<div class="def"><b>Определение.</b> Пусть xα — метка пути от корня до внутреннего узла v (x — символ, α — строка, возможно пустая). Если есть узел s(v) с меткой пути α, указатель v → s(v) называется суффиксной связью. При α = ε связь ведёт в корень.</div>
<div class="thm"><b>Лемма 1.</b> Если в продолжении j создан новый внутренний узел w с меткой пути xα, то в продолжении j + 1 той же фазы путь α либо уже кончается во внутреннем узле, либо такой узел будет создан. Значит, каждый новый внутренний узел получает суффиксную связь к концу следующего продолжения.</div>
<div class="proof"><p>w создан посреди ребра, значит, за xα в дереве шёл единственный символ c ≠ S[i+1]. Путь xαc есть в дереве, поэтому есть и αc (суффиксы строк дерева тоже в дереве). Если α — уже узел, всё доказано. Иначе за α идёт только c, и продолжение j + 1 допишет S[i+1] после α, создав там узел.</p></div>
<p><b>Как пользоваться.</b> Конец S[j−1..i] найден в прошлом продолжении. Поднимаемся от него не больше чем на одно ребро к узлу v, у которого есть суффиксная связь (или к корню); пройденную метку обозначим γ. Если v ≠ корень, идём по связи в s(v) и спускаемся по γ. Если v — корень, спускаемся от корня по S[j..i].</p>

<h3>2. Прыжки по счётчику (skip/count)</h3>
<p>Спускаясь по γ, не сравниваем символы: γ точно есть в дереве. Смотрим только на первый символ (чтобы выбрать ребро) и на длину ребра. Если |γ| ≥ длины ребра — перепрыгиваем его за O(1) и уменьшаем |γ|; иначе останавливаемся внутри ребра на позиции |γ|.</p>
<div class="def"><b>Глубина узла</b> — число узлов на пути от корня до него.</div>
<div class="thm"><b>Лемма 2.</b> При переходе по суффиксной связи (v, s(v)) глубина узла уменьшается не больше чем на 1.</div>
<div class="proof"><p>Каждому внутреннему предку узла v с меткой xβ (β непустая) соответствует его суффиксная связь в узел с меткой β — предок s(v). Разные предки дают разных предков s(v). Без соответствия может остаться только предок с меткой x (его связь ведёт в корень). Значит, depth(s(v)) ≥ depth(v) − 1.</p></div>
<p>Отсюда: за одно продолжение текущая глубина уменьшается не больше чем на 2 (подъём на ребро и переход по связи), а каждый прыжок увеличивает её на 1. Глубина не превосходит m, продолжений в фазе ≤ m, поэтому прыжков в фазе O(m), а с одними связями и прыжками весь алгоритм — O(m²).</p>

<h3>3. Сжатие меток рёбер</h3>
<p>Метка ребра — пара индексов [p, q], а не подстрока. Иначе одни метки могли бы занять Θ(m²) памяти (например, для строки из разных символов). Включи «метки рёбер индексами», чтобы увидеть хранимый вид.</p>

<h3>4. Правило 3 — «стоп» для фазы</h3>
<p>Если в продолжении j применилось правило 3, то путь S[j..i+1] уже в дереве, а значит, есть и все его суффиксы S[j+1..i+1], …. Продолжения j + 1, …, i + 1 тоже закончатся правилом 3, и фазу можно сразу завершить.</p>

<h3>5. Однажды лист — всегда лист</h3>
<p>Созданный лист никогда не перестаёт быть листом, а правило 1 лишь удлиняет его метку на символ. Поэтому у листьев храним метку [p, e], где e — глобальный конец: в начале фазы i + 1 присваиваем e = i + 1, и все продолжения 1…j<sub>i</sub> (листья) выполняются неявно за O(1). Явно выполняются только продолжения j<sub>i</sub> + 1, …, j*, где j* — первое продолжение с правилом 3 (или i + 1).</p>

<h3>Доказательство линейности</h3>
<div class="thm"><b>Теорема.</b> Алгоритм Укконена строит неявное дерево I<sub>m</sub> (для S$ — настоящее суффиксное дерево) за O(m).</div>
<div class="proof">
<p><b>Явные продолжения.</b> В фазе i + 1 явно выполняются продолжения j<sub>i</sub> + 1, …, j*. Следующая фаза начинается с j<sub>i+1</sub> + 1 = j*, то есть с того же продолжения, на котором остановилась эта. Номер явного продолжения никогда не уменьшается, не превосходит m, а между соседними фазами повторяется не больше одного раза. Значит, за все m фаз явных продолжений ≤ 2m.</p>
<p><b>Прыжки.</b> Текущая позиция и её глубина переходят из продолжения в продолжение и из фазы в фазу (конец S[j*..i+1] известен сразу после правила 3). За одно явное продолжение глубина уменьшается не больше чем на 2 (подъём на ребро + суффиксная связь, лемма 2), а каждый прыжок её увеличивает. Так как глубина ≤ m, прыжков за весь алгоритм ≤ m + 2·2m = O(m).</p>
<p><b>Остальное.</b> В каждом явном продолжении, кроме прыжков, O(1) работы: выбрать правило, разделить ребро, добавить лист, поставить связь. Неявные продолжения стоят O(1) на фазу (присваивание e).</p>
<p>Итого O(m) времени и O(m) памяти. Чтобы получить настоящее суффиксное дерево, строим I<sub>m+1</sub> для S$ — ещё одна фаза.</p>
</div>`,
  });
})(window.App);
