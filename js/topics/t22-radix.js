/* Билет 22. Построение суффиксного массива цифровой сортировкой циклических строк (удвоение длины). Индексы с 1. */
(function (App) {
  'use strict';
  const esc = App.esc, { c: C, s: SS } = App.fmt;
  const asc = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

  function run({ T }) {
    const s = T + '$', n = s.length, F = [];
    const cyc = (i) => ((((i - 1) % n) + n) % n) + 1;
    const shift = (i) => s.slice(i - 1) + s.slice(0, i - 1);
    let p = [], c = new Array(n + 1).fill(null), len = 0, stage = 0;
    const rows = (order, o = {}) => order.map((i) => ({ i, c1: c[i], c2: o.pair ? c[cyc(i + len)] : null, cn: o.cn ? o.cn[i] : null }));
    const push = (o) => F.push({ s, n, len, stage, vars: [['n = |T$|', n], ['len', len || '—'], ['классов', c[1] == null ? '—' : Math.max(...c.slice(1))]], ...o });

    push({ line: 0, big: true, msg: `Дописываем $ (меньше всех символов): s = ${SS(s)}, n = ${n}. Сортируем все циклические сдвиги s. Так как $ встречается один раз, сравнение двух сдвигов всегда решается не позже $ — порядок сдвигов совпадает с порядком суффиксов.`, rows: [...Array(n)].map((_, k) => ({ i: k + 1 })), view: 0 });

    // шаг 0: подсчётом по символу
    const alpha = [...new Set(s)].sort(asc);
    const cnt = Object.fromEntries(alpha.map((x) => [x, 0]));
    for (const ch of s) cnt[ch]++;
    for (const x of alpha) for (let i = 1; i <= n; i++) if (s[i - 1] === x) p.push(i);
    let cls = 1;
    p.forEach((i, j) => { if (j && s[i - 1] !== s[p[j - 1] - 1]) cls++; c[i] = cls; });
    len = 1;
    push({ line: 1, big: true, msg: `Длина 1: сортировка подсчётом по первому символу. Количества: ${alpha.map((x) => `${C(x)}×${cnt[x]}`).join(', ')}. Сдвиги выписываем группами по символам в порядке алфавита, внутри группы — в исходном порядке индексов.`, rows: rows(p), view: 1, counts: alpha.map((x) => [x, cnt[x]]) });
    push({ line: 2, msg: `Классы эквивалентности (e.c.) по первому символу: одинаковые символы — один класс, классы нумеруем с 1 по возрастанию. c[i] — класс сдвига i.`, rows: rows(p), view: 1, showC: true });

    while (len < n) {
      stage++;
      push({ line: 3, big: true, msg: `Переход от длины ${len} к ${2 * len}. Первые ${2 * len} символов сдвига i — это две половины длины ${len}: с позиции i и с позиции i + ${len}. Их порядок уже известен по классам, поэтому сдвиг i задаётся парой (c[i], c[i + ${len}]), и сортировать надо пары — цифровой сортировкой: сначала по второму ключу, потом устойчиво по первому.`, rows: rows(p, { pair: true }), view: 2, showC: true });
      const pn = p.map((i) => cyc(i - len));
      push({ line: 4, msg: `Сортировка по второму ключу бесплатна: сдвиги p уже упорядочены по первым ${len} символам, а вторая половина сдвига i начинается в i + ${len}. Поэтому список pn[j] = p[j] − ${len} (циклически) упорядочен по второй половине.`, rows: rows(pn, { pair: true }), view: 2, showC: true, key: 2 });
      const k = Math.max(...c.slice(1)), cc = new Array(k + 1).fill(0);
      for (const i of pn) cc[c[i]]++;
      const start = [];
      cc.reduce((a, v, x) => { start[x] = a; return a + v; }, 0);
      const np = new Array(n);
      const pos = start.slice();
      for (const i of pn) np[pos[c[i]]++] = i;
      push({ line: 5, msg: `Устойчивая сортировка подсчётом по первому ключу c[i]: считаем, сколько сдвигов в каждом классе, получаем начала групп и раскладываем pn по порядку. При равных первых ключах порядок по второму сохраняется — пары отсортированы.`, rows: rows(np, { pair: true }), view: 2, showC: true, key: 1, counts: cc.slice(1).map((v, x) => [`класс ${x + 1}`, `${v} (с № ${start[x + 1] + 1})`]) });
      const cn = new Array(n + 1).fill(null);
      let q = 1;
      np.forEach((i, j) => {
        if (j) { const a = np[j - 1]; if (c[i] !== c[a] || c[cyc(i + len)] !== c[cyc(a + len)]) q++; }
        cn[i] = q;
      });
      push({ line: 6, msg: `Новые классы по первым ${2 * len} символам: идём по отсортированному списку и увеличиваем номер класса, когда пара отличается от предыдущей. Классов стало ${q} из ${n}.`, rows: rows(np, { pair: true, cn }), view: 3, key: 1 });
      p = np; c = cn; len *= 2;
      if (q === n) {
        push({ line: 7, big: true, msg: `Все ${n} классов различны — сдвиги полностью упорядочены, дальше удваивать не нужно (иначе остановились бы, когда len ≥ n).`, rows: rows(p), view: 1, showC: true });
        break;
      }
    }
    const SA = p.slice(1);
    push({ line: 8, big: true, done: true, msg: `Порядок сдвигов p = [${p.join(', ')}]. Первым стоит сдвиг, начинающийся с $ (позиция ${n}), — отбрасываем: SA = [${SA.join(', ')}]. Шагов удвоения ${stage} ≤ ⌈log₂ n⌉, каждый O(n) — всего O(n log n).`, rows: rows(p), view: 4, showC: true, SA });
    return F;
  }

  function render(f) {
    const { s, n, len } = f;
    const shift = (i) => s.slice(i - 1) + s.slice(0, i - 1);
    const pair = f.view === 2 || f.view === 3;
    let h = App.strip(n, [{ type: 'idx', n, base: 1 }, { type: 'chars', label: 's', chars: s }]);
    h += `<table class="sa"><tr><th>№</th><th>i</th><th>циклический сдвиг</th>${pair ? `<th>(c[i], c[i+${len}])</th>` : f.showC ? '<th>класс c[i]</th>' : ''}${f.view === 3 ? '<th>новый класс</th>' : ''}</tr>`;
    f.rows.forEach((r, j) => {
      const w = shift(r.i);
      const cl = (k) => {
        if (f.view === 0) return k === 0 ? 'blk' : '';
        if (pair) return k < len ? (f.key === 1 ? 'blk' : 'pre') : k < 2 * len ? (f.key === 2 ? 'blk' : 'pre') : 'dim';
        return f.done ? '' : k < len ? 'blk' : 'dim';
      };
      const drop = f.done && j === 0;
      const newGroup = f.view === 3 && j > 0 && r.cn !== f.rows[j - 1].cn;
      h += `<tr class="${drop ? 'dim' : ''}"><td class="num">${f.view === 0 ? '' : j + 1}</td><td class="num">${r.i}</td><td class="lft"><span class="str">${[...w].map((ch, k) => `<b class="${cl(k)}">${esc(ch)}</b>`).join('')}</span></td>`;
      if (pair) h += `<td class="num"><span class="${f.key === 1 ? 'new' : ''}">${r.c1}</span>, <span class="${f.key === 2 ? 'new' : ''}">${r.c2}</span></td>`;
      else if (f.showC) h += `<td class="num">${r.c1}</td>`;
      if (f.view === 3) h += `<td class="num${newGroup ? ' new' : ''}">${r.cn}</td>`;
      h += '</tr>';
    });
    h += '</table>';
    if (f.counts) h += `<div class="chips"><b>Подсчёт:</b>${f.counts.map(([a, b]) => `<span>${esc(a)}: ${esc(b)}</span>`).join('')}</div>`;
    if (f.SA) h += `<div class="chips"><b>SA:</b>${f.SA.map((x) => `<span class="ok">${x}</span>`).join('')}</div>`;
    return h;
  }

  App.register({
    id: 'radix', block: 4, num: 22, title: 'Суффиксный массив цифровой сортировкой',
    full: '22. Построение суффиксного массива с помощью цифровой сортировки циклических строк.',
    modes: [{
      id: 'main', label: 'Построение',
      note: 'Как на лекции: индексы и классы эквивалентности (e.c.) нумеруются с 1, $ меньше всех символов.',
      inputs: [{ id: 'T', label: 'Строка T', value: 'ABACABA', max: 11, w: 12 }],
      validate: (v) => (/\$/.test(v.T) ? 'Символ $ зарезервирован под терминатор.' : null),
      presets: [
        { label: 'ABACABA (лекция)', v: { T: 'ABACABA' } },
        { label: 'AAB (лекция)', v: { T: 'AAB' } },
        { label: 'banana', v: { T: 'banana' } },
        { label: 'aaaaaaa', v: { T: 'aaaaaaa' } },
        { label: 'mississippi', v: { T: 'mississippi' } },
      ],
      legend: [['blk', 'ключ, по которому сортируем'], ['pre', 'другая половина'], ['new', 'активный ключ / новый класс']],
      code: [
        's = T$;  n = |s|',
        'p = сортировка подсчётом позиций по символу s[i]',
        'c[i] = класс символа s[i]  (равные — один класс)',
        'for len = 1, 2, 4, …  пока len < n:',
        '  pn[j] = p[j] − len  (циклически)     // уже по 2-й половине',
        '  p = устойчивая сортировка подсчётом pn по c[pn[j]]',
        '  cn: новый класс, когда пара (c[i], c[i+len]) меняется',
        '  c = cn;  если все классы различны — стоп',
        'SA = p без первого элемента (сдвиг с $)',
      ],
      run, render,
    }],
    theory: `
<h3>Идея</h3>
<p>Дописываем к T символ $, который меньше всех символов алфавита: s = T$, n = |s|. Вместо суффиксов сортируем <b>циклические сдвиги</b> s — строки s[i..n]s[1..i−1]. Символ $ встречается в s один раз, поэтому при сравнении двух сдвигов различие найдётся не позже $, и всё, что идёт после $, на результат не влияет. Значит, порядок циклических сдвигов совпадает с порядком суффиксов, и после сортировки остаётся выбросить сдвиг, начинающийся с $.</p>
<p>Удобство сдвигов: у любой циклической подстроки длины 2·len с позиции i две половины — подстроки длины len с позиций i и i + len (по модулю n), и ничего не «выходит за край». Без цикличности строку пришлось бы дополнять символами $ до длины-степени двойки (BACA → BACA$$$$).</p>
<h3>Пример с лекции: ABACABA$</h3>
<ul>
<li><b>Длина 1.</b> Строки по первому символу: $ A A A A B B C, индексы 8 1 3 5 7 2 6 4, классы эквивалентности (e.c.) 1 2 2 2 2 3 3 4.</li>
<li><b>Длина 2.</b> $A, A$, AB, AB, AC, BA, BA, CA → классы 1, 2, 3, 3, 4, 5, 5, 6.</li>
<li><b>Длина 4.</b> Список p − 2 = 6 5 7 3 1 8 4 2 уже упорядочен по второй половине. Его классы первой половины: 5 3 2 4 3 1 6 5. Устойчиво раскладываем по ним и получаем 8 7 5 1 3 6 2 4 с парами (1,5) (2,3) (3,2) (3,5) (4,3) (5,1) (5,6) (6,5). Новые классы 1…8 все различны — готово.</li>
<li>Отбрасываем сдвиг с $ (индекс 8): <b>SA = 7 5 1 3 6 2 4</b>.</li>
</ul>

<h3>Алгоритм (удвоение длины)</h3>
<p>Сортируем сдвиги по первым len символам, len = 1, 2, 4, … Храним:</p>
<ul><li>p — порядок сдвигов (перестановку), отсортированный по первым len символам;</li>
<li>c[i] — класс эквивалентности сдвига i: сдвиги с одинаковыми первыми len символами в одном классе, классы пронумерованы по возрастанию.</li></ul>
<ol>
<li><b>len = 1.</b> Сортировка подсчётом по символу s[i]; классы — номера различных символов по алфавиту. O(n + |Σ|).</li>
<li><b>Переход len → 2·len.</b> Сдвиг i по первым 2·len символам описывается парой (c[i], c[i + len]): сравнить две строки длины 2·len — то же, что сравнить пары лексикографически. Сортируем пары <b>цифровой (поразрядной) сортировкой</b>: сначала по второму ключу, потом устойчиво по первому.
  <ul><li>Сортировка по второму ключу ничего не стоит: p уже упорядочен по первым len символам, а вторая половина сдвига i — это сдвиг i + len. Поэтому pn[j] = p[j] − len (по модулю n) упорядочен по второму ключу.</li>
  <li>Устойчивая сортировка подсчётом pn по c[pn[j]]. Ключи — числа от 0 до n − 1, поэтому O(n).</li>
  <li>Новые классы: проходим по новому p; номер класса увеличиваем, когда пара отличается от предыдущей. O(n).</li></ul></li>
<li>Останавливаемся, когда len ≥ n или все n классов различны. Результат — p без первого элемента.</li>
</ol>

<h3>Корректность</h3>
<div class="proof"><p>Индукция по len. Если классы правильно упорядочивают сдвиги по первым len символам, то для длины 2·len: сдвиг i меньше сдвига j ⇔ (c[i], c[i+len]) лексикографически меньше (c[j], c[j+len]). Первая половина решает, если различна; иначе решает вторая. Цифровая сортировка «сначала младший разряд, потом устойчиво старший» упорядочивает пары лексикографически. Когда len ≥ n, сравнение первых len символов циклических сдвигов — полное сравнение, а значит, и сравнение суффиксов.</p></div>

<h3>Сложность</h3>
<div class="thm"><b>Теорема.</b> Суффиксный массив строится за O(n log n) времени и O(n) памяти.</div>
<div class="proof"><p>Шагов удвоения ⌈log₂ n⌉. Каждый шаг — сортировка подсчётом по ключам из диапазона [0, n) и пересчёт классов, то есть O(n). Начальная сортировка — O(n + |Σ|).</p></div>
<p class="note">Почитать: Гасфилд, гл. 7.14 (суффиксные массивы); сам алгоритм удвоения — Манбер и Майерс.</p>`,
  });
})(window.App);
