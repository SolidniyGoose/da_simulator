/* Билет 2. Сортировка подсчётом (как в конспекте): k = max, P — количества, P′ — префиксные суммы,
   раскладка справа налево: A[i] → B[P′[A[i]]], P′[A[i]]−−. A индексируется с 0, B — с 1. */
(function (App) {
  'use strict';
  const sub = App.fmt.sub;
  const parseNums = (s) => s.split(/[\s,;]+/).filter(Boolean);

  function run({ A: src }) {
    const A = parseNums(src).map(Number), n = A.length, F = [];
    let k = -1;
    const P = [], Pp = [], B = new Array(n).fill(null), from = new Array(n).fill(null);
    const push = (line, msg, x = {}) => F.push({ line, msg, A, k, P: P.slice(), Pp: Pp.slice(), B: B.slice(), from: from.slice(), ...x, vars: [['n', n], ['k', k < 0 ? '—' : k], ...(x.vars || [])] });
    push([], `Сортируем A из n = ${n} целых ключей ≥ 0. Подпись под элементом — его индекс в A: по ней видно, что равные ключи сохраняют порядок (устойчивость).`, { big: true });
    for (let i = 0; i < n; i++) {
      const was = k;
      k = Math.max(k, A[i]);
      push(0, `Этап 1 — максимум: A[${i}] = ${A[i]}${A[i] > was ? ` > ${was < 0 ? '—' : was} → k = ${k}` : ` ≤ k = ${k}`}.`, { ai: i });
    }
    for (let j = 0; j <= k; j++) P[j] = 0;
    push(1, `k = ${k}. Этап 2 — подсчёт: заводим P[0..${k}] = 0 и для каждого элемента увеличиваем P[A[i]].`, { big: true });
    for (let i = 0; i < n; i++) {
      P[A[i]]++;
      push(1, `A[${i}] = ${A[i]} → P[${A[i]}] = ${P[A[i]]}.`, { ai: i, pj: A[i] });
    }
    push(2, `Этап 3 — суммирование: P′[j] = P[0] + … + P[j] — сколько ключей не больше j. Это номер последней позиции в B для ключа j.`, { big: true });
    for (let j = 0; j <= k; j++) {
      Pp[j] = (j ? Pp[j - 1] : 0) + P[j];
      push(2, j ? `P′[${j}] = P′[${j - 1}] + P[${j}] = ${Pp[j - 1]} + ${P[j]} = ${Pp[j]}.` : `P′[0] = P[0] = ${Pp[0]}.`, { ppj: j, pj: j });
    }
    push(3, 'Этап 4 — перекладывание: идём по A справа налево, кладём A[i] в B[P′[A[i]]] и уменьшаем P′[A[i]] на 1.', { big: true });
    for (let i = n - 1; i >= 0; i--) {
      const j = A[i], pos = Pp[j];
      B[pos - 1] = j;
      from[pos - 1] = i;
      Pp[j]--;
      push([3, 4], `i = ${i}, j = A[${i}] = ${j}, P′[${j}] = ${pos}: кладём A[${i}] → B[${pos}] и уменьшаем P′[${j}] до ${Pp[j]}.`, { ai: i, ppj: j, bj: pos - 1 });
    }
    push([], `Готово: B = ${B.join(', ')}. Равные ключи идут в том же порядке, что в A (смотри подписи): идём справа налево и заполняем каждую группу с конца — сортировка устойчива. Время O(n + k): этапы 1, 2, 4 — O(n), этап 3 и обнуление P — O(k).`, { big: true, done: true });
    return F;
  }

  function render(f) {
    const n = f.A.length, K = Math.max(f.k + 1, 1);
    let h = App.strip(n, [
      { type: 'idx', n },
      { type: 'chars', label: 'A', chars: f.A.map(String), cell: (i) => (i === f.ai ? 'blk focus' : f.done ? 'dim' : '') },
    ]);
    if (f.P.length) h += App.strip(K, [
      { type: 'idx', n: K },
      { type: 'nums', label: 'P', values: f.P, cell: (j) => (j === f.pj ? 'new' : '') },
      f.Pp.length ? { type: 'nums', label: 'P′', values: f.Pp.concat(new Array(K - f.Pp.length).fill(null)), cell: (j) => (j === f.ppj ? 'src' : '') } : null,
    ]);
    if (f.B.some((x) => x != null) || f.line === 3) h += App.strip(n, [
      { type: 'idx', n, base: 1 },
      { type: 'chars', label: 'B', chars: f.B.map((x) => (x == null ? ' ' : String(x))), cell: (i) => (i === f.bj ? 'new focus' : f.B[i] != null ? 'ok' : 'ghost') },
      { type: 'nums', label: 'из A', values: f.from.map((x) => (x == null ? null : sub(x))) },
    ]);
    return h;
  }

  App.register({
    id: 'counting', block: 1, num: 2, title: 'Сортировка подсчётом',
    full: '2. Сортировка подсчетом. Доказательство линейности алгоритма.',
    modes: [{
      id: 'main', label: 'Сортировка',
      inputs: [{ id: 'A', label: 'Массив A (целые 0…20)', raw: true, value: '3 2 0 2 2 3 3', max: 60, w: 20 }],
      validate: (v) => { const a = parseNums(v.A); return !a.length || a.length > 16 || a.some((x) => !/^\d+$/.test(x) || +x > 20) ? 'Нужно от 1 до 16 целых чисел от 0 до 20.' : null; },
      presets: [
        { label: 'пример из конспекта', v: { A: '3 2 0 2 2 3 3' } },
        { label: 'с пропусками ключей', v: { A: '5 1 4 1 5 9 2 6' } },
        { label: 'много повторов', v: { A: '2 1 2 0 1 2 0 1' } },
      ],
      legend: [['blk', 'текущий элемент A'], ['new', 'изменилось'], ['src', 'используемое P′'], ['ok', 'уже в B']],
      code: [
        'k = max(A)                                   // O(n)',
        'P[0..k] = 0;  for i: P[A[i]]++               // O(n + k)',
        'P′[j] = P′[j−1] + P[j]                       // O(k)',
        'for i = n − 1 downto 0:                      // справа налево',
        '  j = A[i];  B[P′[j]] = A[i];  P′[j]−−       // O(n)',
      ],
      run, render,
    }],
    theory: `
<h3>Постановка задачи</h3>
<p>Есть неупорядоченный массив A из элементов типа «ключ — значение», где ключ — целое число от 0 до k. Требуется получить упорядоченный массив B из элементов A.</p>
<div class="def"><b>Сортировка подсчётом</b> (counting sort) — устойчивый алгоритм сортировки целых чисел в диапазоне от 0 до некоторой константы k (или объектов с таким ключом), работающий за линейное время.</div>
<div class="def"><b>Устойчивой</b> называется сортировка, которая не меняет порядок одинаковых по компаратору элементов: если в исходном массиве a<sub>i</sub> = a<sub>j</sub>, i ≤ j, то в отсортированном b<sub>i′</sub> = a<sub>i</sub>, b<sub>j′</sub> = a<sub>j</sub> и i′ ≤ j′.</div>
<h3>Алгоритм — 4 этапа</h3>
<ol>
<li><b>Нахождение максимального элемента k.</b></li>
<li><b>Подсчёт количества ключей:</b> массив P, где P[i] — сколько раз ключ i встречается в A.</li>
<li><b>Суммирование:</b> P′[i] — количество ключей в A, не больших i, то есть сумма P[0] + … + P[i].</li>
<li><b>Перекладывание в новый массив B</b> того же размера: проходим A справа налево; для i-го элемента с ключом j = A<sub>i</sub> кладём его в B на позицию P′<sub>j</sub> и уменьшаем P′<sub>j</sub> на 1.</li>
</ol>
<p>Пример из конспекта: A = 3, 2, 0, 2, 2, 3, 3 → P = 1, 0, 3, 3 → P′ = 1, 1, 4, 7 → B = 0, 2, 2, 2, 3, 3, 3.</p>
<h3>Корректность и устойчивость</h3>
<p>P′[j] после суммирования — номер последней позиции, которую в отсортированном массиве займёт ключ j (перед ним P′[j] − 1 ключей не больше j). Каждый раз, кладя ключ j, сдвигаем «последнюю свободную позицию» группы j на 1 влево. Так как идём по A справа налево, последний из равных элементов попадает в конец своей группы, предпоследний — перед ним и т. д. Порядок равных сохраняется.</p>
<h3>Доказательство линейности</h3>
<div class="proof">
<p>Пусть в A n элементов. Тогда:</p>
<ol><li>нахождение максимального элемента k — O(n);</li>
<li>обнуление P — O(k), подсчёт количества ключей — O(n);</li>
<li>суммирование — O(k);</li>
<li>перекладывание — O(n).</li></ol>
<p>Итого O(n + k) времени и O(n + k) дополнительной памяти. Если k = O(n), сортировка линейна. Это не противоречит нижней оценке Ω(n log n): алгоритм не сравнивает элементы, а использует их значения как индексы.</p>
</div>`,
  });
})(window.App);
