/* Билет 5. Бинарные деревья поиска: поиск, вставка, удаление, поворот. */
(function (App) {
  'use strict';

  function run({ ops: src }) {
    const { ops } = App.parseOps(src);
    const T = new App.BT(), F = [];
    let opi = -1;
    const K = (id) => T.N[id].key;
    const push = (line, msg, x = {}) => F.push({
      line, msg, S: T.snap(), opi, ops, ...x,
      vars: [['операция', opi >= 0 && opi < ops.length ? App.opName(ops[opi]) : '—'], ['вершин', T.size()], ['высота h', T.h(T.root)]],
    });

    const search = (k) => {
      push(0, `Поиск ${k}: сравниваем с вершиной, меньше — влево, больше — вправо.`, { big: true });
      const d = App.descend(T, k, push, 0);
      push(0, d.found != null ? `Нашли за ${d.path.length} сравнений — не больше высоты h = ${T.h(T.root)}.` : `Дошли до NULL — ключа ${k} нет.`, { mark: d.found != null ? { [d.found]: 'cur' } : {} });
    };
    const insert = (k) => {
      push(1, `Вставка ${k}: ищем место, как при поиске.`, { big: true });
      const d = App.descend(T, k, push, 1);
      if (d.found != null) { push(1, `Ключ ${k} уже есть.`, { mark: { [d.found]: 'cur' } }); return; }
      const id = T.add(k);
      T.setChild(d.parent, d.side, id);
      push(1, d.parent == null ? `Дерево было пустым — ${k} становится корнем.` : `Новый элемент всегда вставляется в лист: ${k} — ${d.side === 'l' ? 'левый' : 'правый'} сын ${K(d.parent)}. O(h).`, { mark: { [id]: 'new' } });
    };
    const remove = (k) => {
      push(2, `Удаление ${k}: ищем вершину.`, { big: true });
      const d = App.descend(T, k, push, 2);
      if (d.found == null) { push(2, `Ключа ${k} нет.`, {}); return; }
      const z = d.found, Z = T.N[z], p = Z.p, side = p == null ? null : T.side(z);
      if (Z.l == null && Z.r == null) {
        push(3, `${k} — лист: заменяем ссылку у родителя на NULL.`, { mark: { [z]: 'del' }, big: true });
        T.setChild(p, side, null); delete T.N[z];
        push(3, 'Готово.', {});
        return;
      }
      if (Z.l == null || Z.r == null) {
        const c = Z.l ?? Z.r;
        push(4, `У ${k} один сын (${K(c)}): заменяем ссылку у родителя на сына.`, { mark: { [z]: 'del', [c]: 'cur' }, big: true });
        T.setChild(p, side, c); delete T.N[z];
        push(4, `${K(c)} занял место ${k}; порядок ключей сохранился — всё поддерево ${K(c)} лежало с той же стороны от родителя.`, { mark: { [c]: 'cur' } });
        return;
      }
      const s = App.succ(T, z, push, 5);
      push(5, `Два сына: заменяем значение ${k} на значение самой левой вершины в правом сыне (${K(s)} — следующий по величине ключ, поэтому порядок не нарушится) и удаляем её.`, { mark: { [z]: 'cur', [s]: 'del' }, big: true });
      Z.key = K(s);
      const ps = T.N[s].p, ss = T.side(s), c = T.N[s].r;
      T.setChild(ps, ss, c); delete T.N[s];
      push(5, `У самой левой вершины нет левого сына, поэтому её удаление — случай «лист» или «один сын».`, { mark: { [z]: 'cur' } });
    };
    const rotate = (k) => {
      push(6, `Поворот: поднимаем ${k} над его отцом.`, { big: true });
      const d = App.descend(T, k, push, 6);
      if (d.found == null) { push(6, `Ключа ${k} нет.`, {}); return; }
      const x = d.found, p = T.N[x].p;
      if (p == null) { push(6, `${k} — корень, поднимать некуда.`, { mark: { [x]: 'cur' } }); return; }
      const left = T.N[p].l === x, mid = left ? T.N[x].r : T.N[x].l;
      push(left ? 7 : 8, `${k} — ${left ? 'левый' : 'правый'} сын ${K(p)}, поэтому ${left ? 'правый' : 'левый'} поворот: ${k} становится отцом ${K(p)}, ${K(p)} — его ${left ? 'правым' : 'левым'} сыном${mid != null ? `, а ${left ? 'правое' : 'левое'} поддерево ${k} (корень ${K(mid)}) переходит к ${K(p)} ${left ? 'левым' : 'правым'} сыном` : ''}.`, { mark: { [x]: 'rot', [p]: 'rot', ...(mid != null ? { [mid]: 'cur' } : {}) }, big: true });
      T.rotUp(x);
      push(left ? 7 : 8, `Поворот меняет три ссылки — O(1); порядок ключей (симметричный обход) не меняется: ${T.keys().join(', ')}.`, { mark: { [x]: 'cur', [p]: 'rot' } });
    };

    push([], `Операции: ${ops.map(App.opName).join(', ')}. «^7» — поворот, поднимающий 7 над отцом.`, { big: true });
    for (opi = 0; opi < ops.length; opi++) {
      const o = ops[opi];
      ({ '+': insert, '-': remove, '?': search, '^': rotate })[o.t](o.k);
    }
    push([], `Готово. Симметричный обход: ${T.keys().join(', ') || '—'}; высота ${T.h(T.root)}. Без балансировки высота бывает до n (вставь ключи по возрастанию) — это решают AVL и красно-чёрные деревья.`, { big: true });
    return F;
  }

  App.register({
    id: 'bst', block: 2, num: 5, title: 'Бинарные деревья поиска',
    full: '5. Бинарные деревья поиска. Основные операции (поиск, вставка, удаление, поворот).',
    modes: [{
      id: 'main', label: 'Операции',
      note: '«7» — вставка, «-7» — удаление, «?7» — поиск, «^7» — поворот: поднять 7 над отцом.',
      inputs: [{ id: 'ops', label: 'Операции', raw: true, value: '50 30 70 20 40 60 80 35 -30 ^60 ?35', max: 90, w: 28 }],
      validate: (v) => { const r = App.parseOps(v.ops); return r.err || (r.ops.filter((o) => o.t === '+').length > 20 ? 'Не больше 20 вставок.' : null); },
      presets: [
        { label: 'три случая удаления', v: { ops: '50 30 70 20 40 60 80 35 -20 -40 -50' } },
        { label: 'повороты', v: { ops: '50 30 70 20 40 ^30 ^50 ^40' } },
        { label: 'вырождение в список', v: { ops: '10 20 30 40 50 60 ?60' } },
        { label: 'обычный', v: { ops: '50 30 70 20 40 60 80 35 -30 ^60 ?35' } },
      ],
      legend: [['ring', 'текущая вершина / путь'], ['rot', 'поворот'], ['ok', 'новая вершина']],
      code: [
        'поиск: меньше — влево, больше — вправо, равно — нашли; NULL — нет. O(h)',
        'вставка: спуск как в поиске, новый лист. O(h)',
        'удаление: найти вершину, три случая:',
        '  лист → ссылка у родителя = NULL',
        '  один сын → ссылка у родителя = сын',
        '  два сына → значение := самая левая вершина правого сына, удалить её',
        'поворот x над отцом p — O(1):',
        '  x левый сын → правый поворот: p.left = x.right, x.right = p',
        '  x правый сын → левый поворот: p.right = x.left, x.left = p',
      ],
      run,
      render: (f) => App.opsChips(f.ops, f.opi) + App.btree(f.S, { cls: (id) => (f.mark || {})[id] }),
    }],
    theory: `
<div class="def"><b>Определение.</b> Бинарное дерево поиска — бинарное дерево, в котором ключ левого сына меньше ключа вершины, а он меньше ключа правого сына (и так для всех вершин поддеревьев: слева все меньше, справа все больше). Симметричный обход (левое поддерево, вершина, правое) выдаёт ключи по возрастанию.</div>
<p>Пусть h — высота дерева.</p>
<h3>Поиск — O(h)</h3>
<p>Сравниваем с ключом вершины: меньше — идём влево, больше — вправо, равно — нашли; пришли в NULL — ключа нет. Каждый шаг спускает на уровень ниже.</p>
<h3>Вставка — O(h)</h3>
<p>Спускаемся, как при поиске, до NULL и вешаем туда новый элемент: он всегда вставляется в лист.</p>
<h3>Удаление — O(h)</h3>
<ul><li><b>лист</b> — заменяем ссылку у родителя на NULL;</li>
<li><b>один сын</b> — заменяем ссылку у родителя на этого сына;</li>
<li><b>два сына</b> — заменяем значение на значение самой левой вершины в правом сыне (следующий по величине ключ) и удаляем её: у неё нет левого сына, значит, это один из первых двух случаев.</li></ul>
<p>Каждую итерацию алгоритм делает один шаг вниз по дереву и вверх никогда не поднимается — O(h).</p>
<h3>Поворот — O(1)</h3>
<p><b>Правый поворот</b> вокруг ребра p–x (x — левый сын p): x встаёт на место p, p становится правым сыном x, правое поддерево x становится левым поддеревом p. <b>Левый</b> — симметрично. Меняется O(1) указателей, порядок ключей сохраняется. Повороты — основа балансировки AVL, красно-чёрных и декартовых деревьев.</p>
<h3>Высота</h3>
<p>В худшем случае h = n − 1 (ключи вставляли по возрастанию — дерево вырождается в список), тогда все операции O(n). Для случайного порядка вставок ожидаемая высота O(log n). Гарантию O(log n) дают сбалансированные деревья (билеты 6–9).</p>`,
  });
})(window.App);
